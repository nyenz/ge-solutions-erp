// PATH: erp-frontend/scripts/build-gesday.mjs
// fix256: GES DAY page skins. The hand-tuned skin sheets in src/styles/gesday/src-*.css are written without a theme
// prefix (that is how they were designed page by page). This script puts every rule behind :root[data-theme="ges"]
// so the skin only shows when GES DAY is the chosen theme, and writes src/styles/gesday.css (imported in main.jsx).
// Run after changing a src-*.css file:  node scripts/build-gesday.mjs
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import { makeMapper } from './midnight-map.mjs';   // fix280

const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/styles/gesday');
const order = ['src-nh.css', 'src-pay.css', 'src-rx.css', 'src-fd.css', 'src-pg.css', 'src-fix.css'];   // later sheets win, as designed
const P = ':root[data-theme="ges"]';

const scope = (sel) => {
    const s = sel.trim();
    if (s.startsWith(':root')) return P + s.slice(5);
    if (s.startsWith('html')) return 'html[data-theme="ges"]' + s.slice(4);
    return P + ' ' + s;
};

let out = '/* GENERATED by scripts/build-gesday.mjs from src/styles/gesday/src-*.css -- do not edit by hand */\n';
for (const f of order) {
    const root = postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f });
    root.walkRules((rule) => {
        if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
        rule.selectors = rule.selectors.map(scope);
    });
    out += `\n/* ---- ${f} ---- */\n` + root.toString() + '\n';
}
fs.writeFileSync(path.resolve(dir, '../gesday.css'), out);

// fix280: MIDNIGHT (data-theme="gesnavy") = the same skin, rule for rule, with night colours (scripts/midnight-map.mjs).
// MIDNIGHT_HUE / MIDNIGHT_SAT / MIDNIGHT_BASE / MIDNIGHT_OUT let a preview build other finished versions.
const night = makeMapper({
    hue: process.env.MIDNIGHT_HUE ? +process.env.MIDNIGHT_HUE : undefined,
    sat: process.env.MIDNIGHT_SAT ? +process.env.MIDNIGHT_SAT : undefined,
    base: process.env.MIDNIGHT_BASE ? +process.env.MIDNIGHT_BASE : undefined,
});
const N = ':root[data-theme="gesnavy"]';
const scopeN = (sel) => {
    const s = sel.trim();
    if (s.startsWith(':root')) return N + s.slice(5);
    if (s.startsWith('html')) return 'html[data-theme="gesnavy"]' + s.slice(4);
    return N + ' ' + s;
};
let nout = '/* GENERATED by scripts/build-gesday.mjs (fix280) -- MIDNIGHT = GES DAY at night. Do not edit by hand.\n'
    + '   Part 1: the page styles (every .module.css file) turned for the night. Part 2: the GES DAY skin turned for the night\n'
    + '   (comes last, so the hand-tuned skin wins where both speak). */\n';
const isFrame = (rule) => rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name);

// ---- Part 1: every page style that writes a colour by hand (not through a theme token) -----------------------------
// A CSS-module class ".x" in Name.module.css is named "_x_Name-module_<hash>" (vite.config.js), so it is found exactly.
const srcDir = path.resolve(dir, '../..');
const modFiles = [];
const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const p = path.join(d, e.name);
        if (e.isDirectory()) { if (e.name !== 'print') walk(p); }
        else if (e.name.endsWith('.module.css')) modFiles.push(p);
    }
};
walk(srcDir);
modFiles.sort();
const LITERAL = /#(?:[0-9a-fA-F]{3,8})\b|rgba?\(\s*[\d.]+\s*,|\b(?:white|black)\b/;
const COLOR_PROP = /^(background|background-color|background-image|color|-webkit-text-fill-color|fill|stroke|caret-color|border|border-(top|right|bottom|left)(-color)?|border-color|outline|outline-color|box-shadow|text-shadow)$/i;
const inPrint = (node) => { for (let n = node.parent; n; n = n.parent) if (n.type === 'atrule' && /print/i.test(n.params || '')) return true; return false; };
const pageRoot = postcss.root();
for (const file of modFiles) {
    const name = path.basename(file, '.css').replace(/\./g, '-');
    const root = postcss.parse(fs.readFileSync(file, 'utf8'), { from: file });
    root.walkRules((rule) => {
        if (isFrame(rule) || inPrint(rule) || rule.selector.includes(':global')) return;
        const decls = [];
        rule.each((d) => {
            if (d.type !== 'decl' || !COLOR_PROP.test(d.prop)) return;
            const bare = d.value.replace(/var\([^()]*(\([^()]*\)[^()]*)*\)/g, '');   // a colour only inside var(..., fallback) is a token
            if (LITERAL.test(bare)) decls.push(d.clone());
        });
        if (!decls.length) return;
        const sels = rule.selectors
            .filter((x) => /\.[A-Za-z_][\w-]*/.test(x))
            .map((x) => x.replace(/\.([A-Za-z_][\w-]*)/g, (m, c) => `[class*="_${c}_${name}_"]`));
        if (!sels.length) return;
        const r = postcss.rule({ selectors: sels });
        decls.forEach((d) => r.append(d));
        // keep a screen-size wrapper (@media) around the rule
        let host = pageRoot;
        if (rule.parent && rule.parent.type === 'atrule' && /media|supports|container/i.test(rule.parent.name)) {
            host = postcss.atRule({ name: rule.parent.name, params: rule.parent.params });
            pageRoot.append(host);
        }
        host.append(r);
    });
}
pageRoot.walkRules((rule) => { if (!isFrame(rule)) night.learn(rule); });
pageRoot.walkRules((rule) => {
    if (isFrame(rule)) return;
    const before = rule.toString();
    night.apply(rule);
    if (rule.toString() === before) { rule.remove(); return; }
    rule.selectors = rule.selectors.map(scopeN);
});
pageRoot.walkAtRules((a) => { if (!a.nodes || !a.nodes.length) a.remove(); });
nout += '\n/* ==== Part 1: page styles ==== */\n' + pageRoot.toString() + '\n\n/* ==== Part 2: the GES DAY skin ==== */\n';
for (const f of order) {   // first pass: learn which elements sit on a solid accent
    postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f }).walkRules((rule) => { if (!isFrame(rule)) night.learn(rule); });
}
for (const f of order) {
    const root = postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f });
    root.walkRules((rule) => {
        if (isFrame(rule)) return;
        night.apply(rule);
        rule.selectors = rule.selectors.map(scopeN);
    });
    nout += `\n/* ---- ${f} ---- */\n` + root.toString() + '\n';
}
const nfile = process.env.MIDNIGHT_OUT || path.resolve(dir, '../midnight.css');
fs.writeFileSync(nfile, nout);
console.log('wrote', nfile, nout.length, 'bytes');
console.log('wrote src/styles/gesday.css', out.length, 'bytes');
