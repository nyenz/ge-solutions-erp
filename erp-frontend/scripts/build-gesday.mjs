// PATH: erp-frontend/scripts/build-gesday.mjs
// fix256: GES DAY page skins. The hand-tuned skin sheets in src/styles/gesday/src-*.css are written without a theme
// prefix (that is how they were designed page by page). This script puts every rule behind :root[data-theme="ges"]
// so the skin only shows when GES DAY is the chosen theme, and writes src/styles/gesday.css (imported in main.jsx).
// Run after changing a src-*.css file:  node scripts/build-gesday.mjs
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import { makeMapper } from './midnight-map.mjs';   // fix280

const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/styles/gesday');
const order = ['src-nh.css', 'src-pay.css', 'src-rx.css', 'src-fd.css', 'src-pg.css', 'src-fix.css'];   // later sheets win, as designed
const P = ':root[data-theme="ges"]';

const scope = (sel) => {
    const s = sel.trim();
    if (s.startsWith(':root')) return P + s.slice(5);
    if (s.startsWith('html')) return 'html[data-theme="ges"]' + s.slice(4);
    return P + ' ' + s;
};

let out = '/* GENERATED by scripts/build-gesday.mjs from src/styles/gesday/src-*.css -- do not edit by hand */\n';
for (const f of order) {
    const root = postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f });
    root.walkRules((rule) => {
        if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
        rule.selectors = rule.selectors.map(scope);
    });
    out += `\n/* ---- ${f} ---- */\n` + root.toString() + '\n';
}
fs.writeFileSync(path.resolve(dir, '../gesday.css'), out);

// fix280: MIDNIGHT (data-theme="gesnavy") = the same skin, rule for rule, with night colours (scripts/midnight-map.mjs).
// MIDNIGHT_HUE / MIDNIGHT_SAT / MIDNIGHT_BASE / MIDNIGHT_OUT let a preview build other finished versions.
const night = makeMapper({
    hue: process.env.MIDNIGHT_HUE ? +process.env.MIDNIGHT_HUE : undefined,
    sat: process.env.MIDNIGHT_SAT ? +process.env.MIDNIGHT_SAT : undefined,
    base: process.env.MIDNIGHT_BASE ? +process.env.MIDNIGHT_BASE : undefined,
});
const N = ':root[data-theme="gesnavy"]';
const scopeN = (sel) => {
    const s = sel.trim();
    if (s.startsWith(':root')) return N + s.slice(5);
    if (s.startsWith('html')) return 'html[data-theme="gesnavy"]' + s.slice(4);
    return N + ' ' + s;
};
let nout = '/* GENERATED by scripts/build-gesday.mjs (fix280) from src/styles/gesday/src-*.css -- MIDNIGHT = GES DAY at night. Do not edit by hand */\n';
const isFrame = (rule) => rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name);
for (const f of order) {   // first pass: learn which elements sit on a solid accent
    postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f }).walkRules((rule) => { if (!isFrame(rule)) night.learn(rule); });
}
for (const f of order) {
    const root = postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f });
    root.walkRules((rule) => {
        if (isFrame(rule)) return;
        night.apply(rule);
        rule.selectors = rule.selectors.map(scopeN);
    });
    nout += `\n/* ---- ${f} ---- */\n` + root.toString() + '\n';
}
const nfile = process.env.MIDNIGHT_OUT || path.resolve(dir, '../midnight.css');
fs.writeFileSync(nfile, nout);
console.log('wrote', nfile, nout.length, 'bytes');
console.log('wrote src/styles/gesday.css', out.length, 'bytes');
