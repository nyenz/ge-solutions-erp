// PATH: erp-frontend/scripts/build-gesday.mjs
// fix256: GES DAY page skins. The hand-tuned skin sheets in src/styles/gesday/src-*.css are written without a theme
// prefix (that is how they were designed page by page). This script puts every rule behind :root[data-theme="ges"]
// so the skin only shows when GES DAY is the chosen theme, and writes src/styles/gesday.css (imported in main.jsx).
// Run after changing a src-*.css file:  node scripts/build-gesday.mjs
import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';

const dir = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../src/styles/gesday');
const order = ['src-nh.css', 'src-pay.css', 'src-rx.css', 'src-fd.css', 'src-pg.css', 'src-fix.css'];   // later sheets win, as designed
const P = ':root[data-theme="ges"]';

const scope = (sel) => {
    const s = sel.trim();
    if (s.startsWith(':root')) return P + s.slice(5);
    if (s.startsWith('html')) return 'html[data-theme="ges"]' + s.slice(4);
    return P + ' ' + s;
};

let out = '/* GENERATED by scripts/build-gesday.mjs from src/styles/gesday/src-*.css -- do not edit by hand */\n';
for (const f of order) {
    const root = postcss.parse(fs.readFileSync(path.join(dir, f), 'utf8'), { from: f });
    root.walkRules((rule) => {
        if (rule.parent && rule.parent.type === 'atrule' && /keyframes$/i.test(rule.parent.name)) return;
        rule.selectors = rule.selectors.map(scope);
    });
    out += `\n/* ---- ${f} ---- */\n` + root.toString() + '\n';
}
fs.writeFileSync(path.resolve(dir, '../gesday.css'), out);
console.log('wrote src/styles/gesday.css', out.length, 'bytes');
